/**
 * The one theme. `:app`'s `MainActivity` calls this by name, so the name does not change.
 *
 * [dynamicColor] defaults to **false**, changed from the Android Studio scaffold's `true`. Wallpaper
 * extraction replaces the whole scheme on Android 12+, which would make the palette in `Color.kt` —
 * and every contrast decision taken against it — apply to no device that has a wallpaper. The
 * parameter stays so `:app` can opt in deliberately rather than by default.
 */
@Composable
fun PhoneCleanerTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit,
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }

        darkTheme -> DarkColorScheme
        else -> LightColorScheme
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = AppTypography,
        shapes = AppShapes,
        content = content,
    )
}
